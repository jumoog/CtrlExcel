"""Regenerates THIRD-PARTY-LICENSES.txt from the crates the extension links.

    python rust/third_party_licenses.py

Takes the dependency tree from `cargo metadata` (normal dependencies only,
for the Windows and Linux targets the extension is built for) and copies each
crate's license files from the cargo registry. Run it after changing
rust/Cargo.lock.
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, '..', 'THIRD-PARTY-LICENSES.txt')
TARGETS = ['x86_64-pc-windows-msvc', 'x86_64-unknown-linux-gnu']


def linked_packages(target):
    out = subprocess.run(
        ['cargo', 'metadata', '--format-version', '1', '--locked', '--filter-platform', target],
        cwd=HERE, check=True, capture_output=True, text=True).stdout
    meta = json.loads(out)
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    packages = {p['id']: p for p in meta['packages']}
    root = meta['resolve']['root']
    seen, stack = set(), [root]
    while stack:
        pkg = stack.pop()
        if pkg in seen:
            continue
        seen.add(pkg)
        for dep in nodes[pkg]['deps']:
            if any(kind['kind'] is None for kind in dep['dep_kinds']):  # normal, not dev/build
                stack.append(dep['pkg'])
    seen.discard(root)
    return {packages[p]['id']: packages[p] for p in seen}


def license_texts(package):
    directory = os.path.dirname(package['manifest_path'])
    names = sorted(n for n in os.listdir(directory)
                   if n.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'UNLICENSE', 'NOTICE')))
    texts = []
    for name in names:
        path = os.path.join(directory, name)
        if os.path.isfile(path):
            with open(path, encoding='utf-8', errors='replace') as f:
                texts.append((name, f.read().strip()))
    return texts


def main():
    packages = {}
    for target in TARGETS:
        packages.update(linked_packages(target))
    parts = [
        'Third-party software in CtrlExcelReader',
        '=======================================',
        '',
        'The extension is built with these Rust crates (rust/Cargo.lock) and links',
        'them statically (proc-macro crates only run at build time).',
        'Generated by rust/third_party_licenses.py; do not edit.',
        '',
    ]
    missing = []
    for package in sorted(packages.values(), key=lambda p: (p['name'], p['version'])):
        title = f"{package['name']} {package['version']} ({package['license']})"
        parts += ['', title, '-' * len(title), '']
        if package.get('repository'):
            parts += [package['repository'], '']
        texts = license_texts(package)
        if not texts:
            missing.append(package['name'])
            parts.append(f"License: {package['license']} (no license file in the crate)")
        for name, text in texts:
            parts += [f'[{name}]', '', text, '']
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(parts).rstrip() + '\n')
    print(f'{len(packages)} crates written to {os.path.normpath(OUTPUT)}')
    if missing:
        print('without a license file:', ', '.join(missing), file=sys.stderr)


if __name__ == '__main__':
    main()
