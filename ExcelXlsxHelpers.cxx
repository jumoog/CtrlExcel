  // The row as a mapping (unwrapping anytype/mixed), or nullptr if it is not one.
  const MappingVar *asMapping(const Variable *rowVar)
  {
    const Variable *inner = ExcelXlsxHelpers::unwrapAnyOrMixed(rowVar);
    return (inner && inner->isA() == MAPPING_VAR)
      ? static_cast<const MappingVar *>(inner)
      : nullptr;
  }

  // Write a single WinCC OA Variable to a cell. width receives the displayed
  // length for column sizing. False with a reason in problem if the value
  // cannot be stored in Excel. A missing value or an empty text leaves the
  // cell empty (Excel does not store empty strings either).
  bool writeTypedCell(WorkbookWriter &out, uint32_t row, uint32_t column, const Variable *val,
                      size_t &width, std::string &problem)
  {
    width = 0;
    if (!val)
      return true;

    switch (val->isA())
    {
      case INTEGER_VAR:
      case LONG_VAR:
      {
        // Excel stores doubles: integers beyond 2^53 lose precision.
        int64_t v = (val->isA() == INTEGER_VAR)
          ? static_cast<int64_t>(static_cast<const IntegerVar *>(val)->getValue())
          : static_cast<int64_t>(static_cast<const LongVar *>(val)->getValue());
        out.number(row, column, static_cast<double>(v));
        width = numberWidth(static_cast<double>(v));
        return true;
      }
      case FLOAT_VAR:
      {
        double v = static_cast<const FloatVar *>(val)->getValue();
        out.number(row, column, v);
        width = numberWidth(v);
        return true;
      }
      case BIT_VAR:
        out.boolean(row, column, static_cast<const BitVar *>(val)->isTrue());
        width = 5; // "FALSE"
        return true;
      case TIME_VAR:
      {
        const TimeVar *timeVal = static_cast<const TimeVar *>(val);
        double serial = 0.0;
        if (!localTimeToSerial(static_cast<time_t>(timeVal->getSeconds()),
                               timeVal->getMilli(), serial))
        {
          problem = "time cannot be converted to local time";
          return false;
        }
        // Without a date format, Excel shows the serial (e.g. 46105.837...).
        out.number(row, column, serial, CellStyle::DateTime);
        width = 19; // "YYYY-MM-DD hh:mm:ss"
        return true;
      }
      case ANYTYPE_VAR:
      case MIXED_VAR:
        return writeTypedCell(out, row, column, ExcelXlsxHelpers::unwrapAnyOrMixed(val), width, problem);
      default:
      {
        CharString str = (val->isA() == TEXT_VAR)
          ? CharString(static_cast<const TextVar *>(val)->getValue())
          : val->formatValue(CharString());
        std::string text;
        if (!toCellText(str.c_str(), text, width))
        {
          problem = "text exceeds " + std::to_string(EXCEL_MAX_CELL_CHARS) + " characters";
          return false;
        }
        out.text(row, column, text);
        return true;
      }
    }
  }
