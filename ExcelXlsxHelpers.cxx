  void readSheetRows(Workbook &book, const std::string &sheetName, DynVar &result,
                     bool useHeaders, bool skipHidden, bool skipEmpty,
                     std::vector<std::string> &warnings)
  {
    RowBuilder builder(result, useHeaders, skipHidden, skipEmpty);
    book.readSheet(sheetName, builder);
    builder.finish(warnings);
  }

  // Columns are the keys of all rows in order of first appearance; row 1
  // holds them as bold headers.
  bool writeSheetData(WorkbookWriter &out, const DynVar &data, std::string &error)
  {
    unsigned int numRows = data.getNumberOfItems();
    if (numRows == 0)
      return true;

    // Validate every row before writing.
    std::vector<const MappingVar *> rows;
    rows.reserve(numRows);
    for (unsigned int r = 0; r < numRows; r++)
    {
      const MappingVar *row = asMapping(data.getAt(r));
      if (!row)
      {
        error = "row " + std::to_string(r + 1) + " is not a mapping";
        return false;
      }
      rows.push_back(row);
    }

    // Union of all keys, so keys missing from the first row are not dropped.
    // Lookups use the original key Variables: stringified TextVar keys would
    // miss non-text keys such as the int column keys readSheetRows produces.
    MappingVar seenKeys;
    std::vector<const Variable *> keys;
    for (const MappingVar *row : rows)
    {
      for (unsigned int k = 0; k < row->getNumberOfItems(); k++)
      {
        const Variable *key = row->getKey(k);
        if (!seenKeys.getAt(*key))
        {
          seenKeys.setAt(*key, BitVar(true));
          keys.push_back(key);
        }
      }
    }

    size_t numCols = keys.size();
    if (numCols == 0)
      return true;

    // Excel's sheet size; checked up front so nothing is half-written.
    if (numRows + 1 > EXCEL_MAX_ROWS)
    {
      error = std::to_string(numRows) + " rows exceed Excel's limit of "
            + std::to_string(EXCEL_MAX_ROWS - 1) + " data rows";
      return false;
    }
    if (numCols > EXCEL_MAX_COLUMNS)
    {
      error = std::to_string(numCols) + " columns exceed Excel's limit of "
            + std::to_string(EXCEL_MAX_COLUMNS);
      return false;
    }

    // Max displayed width per column, starting with the header.
    std::vector<size_t> maxWidths(numCols);
    std::vector<std::string> headerNames(numCols);

    for (size_t c = 0; c < numCols; c++)
    {
      CharString name = keys[c]->formatValue(CharString());
      if (!toCellText(name.c_str(), headerNames[c], maxWidths[c]))
      {
        error = "column header exceeds " + std::to_string(EXCEL_MAX_CELL_CHARS) + " characters";
        return false;
      }
      out.text(1, static_cast<uint32_t>(c + 1), headerNames[c], CellStyle::Header);
    }

    for (unsigned int r = 0; r < numRows; r++)
    {
      for (size_t c = 0; c < numCols; c++)
      {
        const Variable *cellVal = rows[r]->getAt(*keys[c]);
        size_t width = 0;
        std::string problem;
        if (!writeTypedCell(out, r + 2, static_cast<uint32_t>(c + 1), cellVal, width, problem))
        {
          error = "row " + std::to_string(r + 1) + ", column '"
                + headerNames[c] + "': " + problem;
          return false;
        }
        if (width > maxWidths[c])
          maxWidths[c] = width;
      }
    }

    // Character width plus padding; the writer caps it at Excel's maximum.
    for (size_t c = 0; c < numCols; c++)
      out.columnWidth(static_cast<uint32_t>(c + 1), static_cast<double>(maxWidths[c]) + 2.0);

    return true;
  }

  void convertRowsToProjectEncoding(DynVar &rows, std::vector<std::string> &warnings)
  {
    if (Resources::isUtf8Encoding())
      return;

    // Text keys converted once each and de-duplicated after conversion:
    // characters the codepage lacks can merge distinct UTF-8 names.
    std::unordered_map<std::string, std::string> keyMap; // UTF-8 -> project
    std::unordered_set<std::string> usedKeys;
    auto convertKey = [&](const std::string &utf8) -> const std::string &
    {
      auto known = keyMap.find(utf8);
      if (known != keyMap.end())
        return known->second;

      if (!isRepresentable(utf8))
        warnings.push_back("header '" + utf8 + "' cannot be represented in the project encoding");

      std::string base = fromUtf8(utf8).c_str();
      std::string unique = base;
      for (int n = 2; !usedKeys.insert(unique).second; ++n)
        unique = base + "_" + std::to_string(n);
      return keyMap.emplace(utf8, unique).first->second;
    };

    for (unsigned int r = 0; r < rows.getNumberOfItems(); r++)
    {
      const Variable *rowVar = rows.getAt(r);
      if (!rowVar || rowVar->isA() != MAPPING_VAR)
        continue;

      const MappingVar &row = *static_cast<const MappingVar *>(rowVar);
      MappingVar *converted = new MappingVar;
      for (unsigned int k = 0; k < row.getNumberOfItems(); k++)
      {
        const Variable *key = row.getKey(k);
        const Variable *value = row.getValue(k);

        Variable *newKey = (key->isA() == TEXT_VAR)
          ? new TextVar(convertKey(static_cast<const TextVar *>(key)->getValue()).c_str())
          : key->clone();
        Variable *newValue = (value->isA() == TEXT_VAR)
          ? new TextVar(fromUtf8(static_cast<const TextVar *>(value)->getValue()).c_str())
          : value->clone();
        converted->setAt(newKey, newValue); // takes ownership
      }
      delete rows.replaceAt(r, converted);
    }
  }
