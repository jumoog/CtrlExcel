  // Cell text from project-encoded text, as valid UTF-8; width receives the
  // length in characters. False if the text exceeds Excel's per-cell limit.
  bool toCellText(const char *projectText, std::string &out, size_t &width)
  {
    out = toValidUtf8(ExcelXlsxHelpers::toUtf8(projectText).c_str());
    width = utf16Length(out);
    return width <= EXCEL_MAX_CELL_CHARS;
  }

  // Sets key to value in row, which takes ownership of value. The cloning
  // setAt(const Variable &, const Variable &) would copy every value once more.
  void put(MappingVar &row, const Variable &key, Variable *value)
  {
    row.setAt(key.clone(), value);
  }

  void setNumber(MappingVar &row, const Variable &key, double value)
  {
    int64_t integer = 0;
    switch (integerFit(value, integer))
    {
      case IntegerFit::Int:
        put(row, key, new IntegerVar(static_cast<int>(integer)));
        break;
      case IntegerFit::Long:
        put(row, key, new LongVar(integer));
        break;
      default:
        put(row, key, new FloatVar(value));
        break;
    }
  }

  // Set a mapping value from a cell. Returns false for a cell without a
  // value. A formula without a cached result (files generated by tools and
  // never recalculated by Excel) reads as "" but counts as content. A date
  // CTRL cannot hold reads as its Excel serial. Texts stay UTF-8: reads may
  // run on worker threads, and WinCC OA's encoding converter is only used on
  // the CTRL thread (convertRowsToProjectEncoding).
  bool setCell(MappingVar &row, const Variable &key, const cxlsx_cell &cell, ReadState &state)
  {
    switch (cell.type)
    {
      case CXLSX_UNCACHED_FORMULA:
        put(row, key, new TextVar(""));
        ++state.uncachedFormulas;
        return true;

      case CXLSX_DATETIME:
        if (isDateCell(cell))
        {
          std::tm tm{};
          PVSSshort milli = 0;
          time_t sec = 0;
          LocalTime converted = serialToLocalTime(cell.number, tm, milli, sec, TimeVar::MaxTimeVarSec, state);
          if (converted == LocalTime::OutOfRange)
          {
            put(row, key, new FloatVar(cell.number));
            ++state.unrepresentableDates;
          }
          else
          {
            put(row, key, new TimeVar(sec, milli));
            if (converted == LocalTime::Shifted)
              ++state.shiftedTimes;
          }
          return true;
        }
        setNumber(row, key, cell.number); // time of day only
        return true;

      case CXLSX_NUMBER:
      case CXLSX_DURATION: // elapsed time: a number of days
        setNumber(row, key, cell.number);
        return true;

      case CXLSX_BOOL:
        put(row, key, new BitVar(cell.boolean));
        return true;

      case CXLSX_TEXT:
        put(row, key, new TextVar(cell.text ? cell.text : "", cell.text_len));
        return true;

      case CXLSX_ERROR:
        // Keep Excel's error code (#DIV/0!, #N/A, ...) so a failed formula is
        // distinguishable from an empty cell.
        put(row, key, cell.text_len ? new TextVar(cell.text, cell.text_len) : new TextVar("#ERROR"));
        return true;

      default:
        put(row, key, new TextVar(""));
        return false;
    }
  }

  // Builds the rows of a sheet from what Workbook::readSheet delivers: the
  // rows stored in the sheet, each with its cells that have a value.
  class RowBuilder : public SheetVisitor
  {
  public:
    RowBuilder(DynVar &result, bool useHeaders, bool skipHidden, bool skipEmpty)
      : m_result(result), m_skipHidden(skipHidden), m_skipEmpty(skipEmpty),
        m_dataStartRow(useHeaders ? 2 : 1), m_nextRow(m_dataStartRow)
    {
    }

    bool begin(uint32_t rows, uint32_t columns) override
    {
      m_colCount = static_cast<uint16_t>(std::min(columns, EXCEL_MAX_COLUMNS));
      // Nothing to read; with only a header row there are no records either.
      if (rows < m_dataStartRow || m_colCount == 0)
        return false;
      m_keys.resize(m_colCount);
      return true;
    }

    bool row(uint32_t number, bool hidden) override
    {
      finishRow();
      if (number < m_dataStartRow)
      {
        m_inHeader = true; // row 1 with headers on, hidden or not
        return true;
      }

      finishKeys();
      // Rows that do not exist still count when empty rows are kept, so the
      // result index keeps mapping to the Excel row.
      if (!m_skipEmpty)
        for (; m_nextRow < number; ++m_nextRow)
          m_result.append(m_emptyRow);
      m_nextRow = number + 1;

      if (m_skipHidden && hidden)
        return true;

      m_inRow = true;
      m_row.reset(new MappingVar);
      m_hasValue = false;
      m_lastColumn = 0;
      return true;
    }

    bool cell(const cxlsx_cell &cell) override
    {
      if (cell.column == 0 || cell.column > m_colCount)
        return true;
      const uint16_t column = static_cast<uint16_t>(cell.column);

      if (m_inHeader)
      {
        // One mapping key per column: the header text, or the 1-based column
        // number when headers are off or a header cell is empty (finishKeys).
        // Repeated headers get a numeric suffix ("Value", "Value_2") so no
        // two columns share a key and overwrite each other.
        std::string name = headerText(cell, m_state);
        if (name.empty() || m_keys[column - 1])
          return true;
        // UTF-8 key; convertRowsToProjectEncoding converts it (and resolves
        // names that collide only after conversion) on the CTRL thread.
        std::string unique = name;
        for (int n = 2; !m_seenHeaders.insert(unique).second; ++n)
          unique = name + "_" + std::to_string(n);
        m_keys[column - 1].reset(new TextVar(unique.c_str()));
        return true;
      }

      if (!m_inRow || column <= m_lastColumn)
        return true;
      while (++m_lastColumn < column)
        put(*m_row, *m_keys[m_lastColumn - 1], new TextVar(""));
      m_hasValue = setCell(*m_row, *m_keys[column - 1], cell, m_state) || m_hasValue;
      return true;
    }

    // After the last row; adds the warnings of the read.
    void finish(std::vector<std::string> &warnings)
    {
      finishRow();

      if (m_state.unrepresentableDates > 0)
        warnings.push_back(std::to_string(m_state.unrepresentableDates)
                           + " date cell(s) lie outside the range of CTRL time (1970 to 2262) and "
                             "read as their Excel serial number (float)");
      if (m_state.shiftedTimes > 0)
        warnings.push_back(std::to_string(m_state.shiftedTimes)
                           + " time(s) fall into the hour skipped when daylight saving time starts "
                             "and were moved to the next valid time");
      if (m_state.uncachedFormulas > 0)
        warnings.push_back(std::to_string(m_state.uncachedFormulas)
                           + " formula cell(s) have no calculated value and read as \"\"; "
                             "open and save the file in Excel to calculate them");
    }

  private:
    // Before the first data row: columns without a header text get their
    // 1-based number as key.
    void finishKeys()
    {
      if (m_keysDone)
        return;
      m_keysDone = true;
      for (uint16_t c = 0; c < m_colCount; ++c)
        if (!m_keys[c])
          m_keys[c].reset(new IntegerVar(c + 1));
      if (!m_skipEmpty)
        for (const auto &key : m_keys)
          m_emptyRow.setAt(*key, TextVar(""));
    }

    void finishRow()
    {
      m_inHeader = false;
      if (!m_inRow)
        return;
      m_inRow = false;
      while (++m_lastColumn <= m_colCount)
        put(*m_row, *m_keys[m_lastColumn - 1], new TextVar(""));
      // A sheet's rows include rows that only carry formatting (fill,
      // height); by default rows without any value are not records.
      // append(VariablePtr) takes the row over; append(const Variable &)
      // would copy it with all its keys and values.
      if (m_hasValue || !m_skipEmpty)
        m_result.append(m_row.release());
      m_row.reset();
    }

    DynVar &m_result;
    const bool m_skipHidden;
    const bool m_skipEmpty;
    const uint32_t m_dataStartRow;

    uint16_t m_colCount = 0;
    std::vector<std::unique_ptr<Variable>> m_keys;
    std::unordered_set<std::string> m_seenHeaders;
    bool m_keysDone = false;
    MappingVar m_emptyRow; // every key "", for rows the sheet does not store
    ReadState m_state;

    uint32_t m_nextRow;        // Excel row the next result entry stands for
    bool m_inHeader = false;
    bool m_inRow = false;      // a data row is being built in m_row
    std::unique_ptr<MappingVar> m_row;
    bool m_hasValue = false;
    uint16_t m_lastColumn = 0; // columns of m_row set so far
  };

